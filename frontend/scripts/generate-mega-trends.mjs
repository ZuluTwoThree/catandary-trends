#!/usr/bin/env node
/**
 * Generates frontend/src/lib/mega-trends.generated.ts from ../mega_trends.yaml.
 * Run automatically via `predev` / `prebuild` npm scripts.
 * Single source of truth: mega_trends.yaml at the repo root.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const YAML_PATH = path.resolve(__dirname, "..", "..", "mega_trends.yaml");
const OUT_PATH = path.resolve(__dirname, "..", "src", "lib", "mega-trends.generated.ts");

const raw = fs.readFileSync(YAML_PATH, "utf-8");
const data = yaml.load(raw);
const trends = data?.mega_trends ?? [];

const items = trends.map((mt) => ({
  key: mt.key,
  name_en: mt.name_en,
  description_en: mt.description ?? "",
  icon: mt.icon ?? "📊",
  verticals: mt.verticals ?? [],
  // Earned Megatrend badge + the measurement backing it (written by
  // scripts/measure_mega_axes.py --write-yaml; owner rule 2026-08-08:
  // reach >= 0.50, all 4 tiers, early-tier lead > 0, curation veto respected)
  megatrend: Boolean(mt.megatrend),
  measured: mt.measured ?? null,
}));

const header = `// AUTO-GENERATED by frontend/scripts/generate-mega-trends.mjs
// Source of truth: mega_trends.yaml at the repo root. Do not edit by hand.
import type { MegaTrendInfo } from "./types";

export const MEGA_TRENDS: MegaTrendInfo[] = ${JSON.stringify(items, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, header, "utf-8");
console.log(`Generated ${OUT_PATH} with ${items.length} mega-trends.`);
